function availabilityFrom(startOffsetDays: number): Consultant["availability"] {
  const days = [];
  const base = new Date("2026-08-05T00:00:00Z");
  for (let i = 0; i < 6; i++) {
    const d = new Date(base);
    d.setDate(base.getDate() + startOffsetDays + i * 2);
    days.push({
      date: d.toISOString().slice(0, 10),
      times: ["09:00", "10:30", "14:00", "16:30"].filter((_, idx) => (i + idx) % 3 !== 0),
    });
  }
  return days;
}

